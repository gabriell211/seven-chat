-- Social actions and direct messages are persisted; no fake profiles or messages.
ALTER TABLE accounts ADD COLUMN bio VARCHAR(160) NOT NULL DEFAULT '';

CREATE TABLE follows (
  follower_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  following_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (follower_id, following_id),
  CONSTRAINT ck_follows_distinct CHECK (follower_id <> following_id)
);
CREATE INDEX ix_follows_following ON follows(following_id);

CREATE TABLE user_blocks (
  blocker_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  blocked_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (blocker_id, blocked_id),
  CONSTRAINT ck_blocks_distinct CHECK (blocker_id <> blocked_id)
);
CREATE INDEX ix_blocks_blocked ON user_blocks(blocked_id);

CREATE TABLE post_likes (
  account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (account_id, post_id)
);
CREATE INDEX ix_likes_post ON post_likes(post_id);

CREATE TABLE post_saves (
  account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (account_id, post_id)
);

CREATE TABLE post_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  author_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  body VARCHAR(500) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_comments_post_id ON post_comments(post_id, id DESC);

CREATE TABLE direct_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  receiver_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  client_mutation_id UUID NOT NULL,
  body VARCHAR(4000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_messages_distinct CHECK (sender_id <> receiver_id),
  CONSTRAINT uq_messages_mutation UNIQUE(sender_id, client_mutation_id)
);
CREATE INDEX ix_messages_inbox ON direct_messages(receiver_id, id DESC);
CREATE INDEX ix_messages_outbox ON direct_messages(sender_id, id DESC);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  actor_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  event_type VARCHAR(24) NOT NULL,
  resource_id BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  seen_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_notifications_account ON notifications(account_id, id DESC);
