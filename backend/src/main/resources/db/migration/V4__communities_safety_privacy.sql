-- Real community spaces, user reporting and privacy actions.
-- Each reference to a user cascades on account deletion for verified erasure.
CREATE TABLE chat_groups (
    id UUID PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(240) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_group_name CHECK (length(btrim(name)) >= 3)
);
CREATE INDEX ix_groups_owner ON chat_groups(owner_id);

CREATE TABLE group_members (
    group_id UUID NOT NULL REFERENCES chat_groups(id) ON DELETE CASCADE,
    account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (group_id, account_id)
);
CREATE INDEX ix_group_members_account ON group_members(account_id, group_id);

CREATE TABLE group_invitations (
    id UUID PRIMARY KEY,
    group_id UUID NOT NULL REFERENCES chat_groups(id) ON DELETE CASCADE,
    inviter_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    invitee_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (group_id, invitee_id),
    CONSTRAINT ck_invite_distinct CHECK (inviter_id <> invitee_id)
);
CREATE INDEX ix_group_invitations_inbox ON group_invitations(invitee_id, status);

CREATE TABLE group_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id UUID NOT NULL REFERENCES chat_groups(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    client_mutation_id UUID NOT NULL,
    body VARCHAR(4000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (sender_id, client_mutation_id)
);
CREATE INDEX ix_group_messages_recent ON group_messages(group_id, id DESC);

CREATE TABLE moderation_roles (
    account_id UUID PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE moderation_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    target_type VARCHAR(16) NOT NULL CHECK (target_type IN ('account','post','group_message')),
    target_id VARCHAR(64) NOT NULL,
    category VARCHAR(20) NOT NULL
        CHECK (category IN ('spam','harassment','hate','violence','nudity','scam','other')),
    details VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(12) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN','REVIEWING','RESOLVED','DISMISSED')),
    reviewer_id UUID REFERENCES accounts(id) ON DELETE SET NULL,
    review_notes VARCHAR(1000),
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(reporter_id,target_type,target_id)
);
CREATE INDEX ix_moderation_reports_queue ON moderation_reports(status,id DESC);
CREATE INDEX ix_moderation_reports_owner ON moderation_reports(reporter_id,id DESC);

CREATE TABLE privacy_consents (
    account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    consent_type VARCHAR(16) NOT NULL CHECK (consent_type IN ('terms','privacy','marketing')),
    document_version VARCHAR(32) NOT NULL,
    granted BOOLEAN NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(account_id,consent_type)
);
